def load(path):
    data = json.loads(path.read_text())
    if data.get("status") != "PASS" or not data.get("schema", "").startswith(
        "synkit.crn-"
    ):
        raise ValueError(f"Invalid evidence: {path}")
    return data


ALIASES = {
    "reversible_isomerization": "Reversible isomerization",
    "irreversible_isomerization": "Irreversible isomerization",
    "isomerization_cycle": "Isomerization cycle",
    "disjoint_reversible_blocks": "Disconnected reversible pairs",
    "disjoint_blocks_with_stoichiometry": "Pairs with stoichiometry",
    "michaelis_menten": "Michaelis–Menten",
    "reversible_michaelis_menten": "Reversible Michaelis–Menten",
    "edelstein": "Edelstein switch",
    "futile_cycle_1_site": "Phosphorylation: one site",
    "futile_cycle_2_site": "Phosphorylation: two sites",
    "shinar_feinberg_acr": "Shinar–Feinberg motif",
    "open_inflow_outflow": "Open reactor",
}
SHARED = [
    "n_species",
    "n_reactions",
    "n_complexes",
    "n_linkage_classes",
    "rank",
    "deficiency",
    "weakly_reversible",
    "linkage_class_deficiencies",
]


def reference_table(validation, external):
    """Return the reference-network invariants as booktabs rows for main.tex.

    Every network passes and agrees with CRNT4SBML on all shared quantities, so
    those constant columns are asserted here and stated once in the caption.
    """
    external_by_name = {r["name"]: r for r in external["networks"]}
    rows = []
    for row in validation["networks"]:
        assert row["passed"] and not row["mismatches"] and not row["crosscheck_failures"]
        ext = external_by_name[row["name"]]
        assert all(ext["synkit"][k] == ext["crnt4sbml"][k] for k in SHARED)
        c = row["computed"]
        cells = [ALIASES[row["name"]].replace("–", "--")] + [
            str(c[k]) for k in ("n_species", "n_reactions", "n_complexes",
                                "n_linkage_classes", "rank", "deficiency",
                                "n_conservation_laws")
        ] + ["yes" if c["weakly_reversible"] else "no"]
        rows.append(" & ".join(cells) + r" \\")
    return ("% Generated by analysis_overview.py from crn-validation.json.\n"
            + "\n".join(rows) + "\n")


def concept_panel(ax):
    """What panels b and c count, drawn on the enzyme scheme of Figure 1.

    A siphon that holds the support of a conserved pool cannot empty, which is
    the persistence test applied to every enumerated siphon.
    """
    siphons = minimal_siphons(ENZYME_SPECIES, ENZYME_REACTIONS)
    pools = minimal_pools(ENZYME_SPECIES, ENZYME_REACTIONS)
    assert sorted(map(sorted, siphons)) == [["E", "ES"], ["ES", "S"]]
    assert sorted(map(sorted, pools)) == [["E", "ES"], ["ES", "P", "S"]]
    ax.set(xlim=(-0.6, 13.4), ylim=(-1.75, 1.15), aspect="equal")
    ax.axis("off")
    plain_heading(ax, "a", y=0.98, x=0.0)
    for x0, members, covered, line in (
        (0.3, {"E", "ES"}, True, "siphon {E, ES} contains the pool E + ES"),
        (7.6, {"S", "ES"}, False, "siphon {S, ES} contains no pool"),
    ):
        assert members in siphons
        assert covered == any(pool <= members for pool in pools)
        enzyme_net(ax, x0, 0.05, highlight=members, scale=1.0)
        verdict(ax, x0 + 4.75, 0.05, covered, 10, vector=True)
        ax.text(x0 + 1.95, -1.05, line, ha="center", va="top", fontsize=8.5,
                style="italic")


def biomodels_panel(ax, evidence):
    models = sorted(
        (r for r in evidence["models"] if r["n_reactions"] > 0),
        key=lambda r: r["n_species"],
    )
    for key, filled, marker, label in (("siphon_seconds", True, "o", "Minimal siphons"),
                                       ("moiety_seconds", False, "s", "Conserved pools")):
        pts = [(r["n_species"], r[key]) for r in models if r[key] is not None]
        if pts:
            ax.scatter(*zip(*pts), s=16, marker=marker, zorder=3, label=label,
                       facecolor="black" if filled else "white",
                       edgecolor="black", lw=0.6)
    for r in models:
        if r["siphon_seconds"] is None and "node_limit" in r.get("siphon_error", ""):
            ax.scatter(r["n_species"], 0.025, transform=ax.get_xaxis_transform(),
                       marker="x", s=28, color=BLUE, zorder=5, clip_on=False)
            ax.annotate("node cap", (r["n_species"], 0.025),
                        xycoords=ax.get_xaxis_transform(), xytext=(0, 9),
                        textcoords="offset points", ha="center", fontsize=7, color=BLUE)
        for field, marker, color in (("moiety_seconds", "s", GRAY), ("siphon_seconds", "o", BLUE)):
            error_field = "moiety_error" if field == "moiety_seconds" else "siphon_error"
            if r[field] is None and r.get(error_field) == "timeout":
                ax.scatter(r["n_species"], 120, s=26, marker=marker,
                           facecolor="white", edgecolor=color, lw=1.0, zorder=4)
                ax.annotate("", (r["n_species"], 120 * 6), (r["n_species"], 120 * 1.25),
                            arrowprops=dict(arrowstyle="-|>", color=color, lw=0.9))
    ax.set(xscale="log", yscale="log", xlim=(5, 800), ylim=(5e-5, 300),
           xlabel="Species in model", ylabel="Wall time (s)")
    ax.set_xticks([10, 100], labels=["10", "100"])
    ax.set_yticks([1e-4, 1e-2, 1, 100])
    ax.minorticks_off()
    ax.legend(loc="upper left", bbox_to_anchor=(0.0, 0.98), handletextpad=0.3,
              borderaxespad=0.6, borderpad=0.4)
    inset_label(ax, "b")


def kegg_panel(ax, evidence):
    names = {
        "M00001": "Glycolysis",
        "M00307": "Pyruvate oxidation",
        "M00009": "Citrate cycle",
        "M00004": "Pentose phosphate",
    }
    colors = [BLUE] * 4
    modules = evidence["modules"]
    # Each row is one module: the gray track spans its species, and one dot per
    # minimal pool sits at the pool size, stacked when sizes coincide.
    step = 0.12
    for i, (row, color) in enumerate(zip(modules, colors)):
        ax.plot([0, row["n_species"]], [i, i], color="black", lw=0.4,
                ls=(0, (1, 1.5)), zorder=1)
        ax.plot([row["n_species"]] * 2, [i - 0.16, i + 0.16], color="black",
                lw=0.6, zorder=1)
        ax.text(row["n_species"] + 0.4, i, str(row["n_species"]), va="center",
                fontsize=8)
        sizes = sorted(len(pool) for pool in row["moieties"])
        for size in set(sizes):
            count = sizes.count(size)
            ys = i + (np.arange(count) - (count - 1) / 2) * step
            ax.scatter([size] * count, ys, s=11, color="black", lw=0, zorder=3)
        ax.text(-0.03, i, names[row["module_id"]], transform=ax.get_yaxis_transform(),
                ha="right", va="center", fontsize=8.5)
        ax.text(-0.03, i + 0.3, f"$\\delta = {row['deficiency']}$",
                transform=ax.get_yaxis_transform(), ha="right", va="center",
                fontsize=8)
    ax.set(
        xlim=(0, 24.5),
        ylim=(len(modules) - 0.5, -0.6),
        xticks=[1, 5, 10, 15, 20],
        yticks=[],
        xlabel="Species in conserved pool",
    )
    ax.minorticks_off()
    ax.tick_params(axis="y", which="both", left=False, right=False)
    inset_label(ax, "c", x=0.9)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--evidence-dir", type=Path, default=Path("analysis"))
    parser.add_argument(
        "--output", type=Path, default=Path("Figure/analysis_overview.pdf")
    )
    args = parser.parse_args()
    configure()
    e = args.evidence_dir
    validation = load(e / "crn-validation.json")
    external = load(e / "crn-external-crnt4sbml.json")
    biomodels = load(e / "crn-biomodels.json")
    kegg = load(e / "crn-kegg.json")
    reference_table(validation, external)
    fig = plt.figure(figsize=(7.2, 4.4))
    concept_panel(fig.add_axes([0.02, 0.70, 0.96, 0.28]))
    a = fig.add_axes([0.10, 0.10, 0.33, 0.53])
    b = fig.add_axes([0.66, 0.10, 0.32, 0.53])
    biomodels_panel(a, biomodels)
    kegg_panel(b, kegg)
    save(fig, args.output.parent, args.output.stem)


if __name__ == "__main__":
    main()
